/** Хаб по slug адреса или undefined, если такого хаба нет. */
export function findTopicHub(slug: string): TopicHub | undefined {
  return TOPIC_HUBS.find((h) => h.slug === slug);
}

/**
 * Опубликованные статьи хаба в порядке postSlugs. Снятые или ещё не опубликованные
 * slug пропускаются молча: хаб не должен падать из-за одной статьи.
 */
export function hubPosts<T extends { slug: string }>(hub: TopicHub, published: readonly T[]): T[] {
  const bySlug = new Map(published.map((p) => [p.slug, p]));
  return hub.postSlugs.map((s) => bySlug.get(s)).filter((p): p is T => p !== undefined);
}
