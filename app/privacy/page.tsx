import type { Metadata } from 'next';
import Link from 'next/link';
import { getSystemSettings } from '@/lib/settings';
import { buildPublicPageMetadata } from '@/lib/seo/metadata-helpers';
import { DEFAULT_OG_IMAGE_PATH } from '@/lib/seo/pages';
import { normalizeSiteUrl } from '@/lib/site-url';
import { getPdnOperatorPublic } from '@/lib/pdn-public';
import { PDN_DOCS_VERSION } from '@/lib/consent-log';

const DESCRIPTION =
  'Политика в отношении обработки персональных данных на сайте AVATERRA (avaterra.pro): цели, состав данных, cookies, аналитика, права субъектов, порядок обращений.';

export async function generateMetadata(): Promise<Metadata> {
  const settings = await getSystemSettings();
  const base = normalizeSiteUrl(settings.site_url || 'https://avaterra.pro').replace(/\/$/, '');
  const canonical = `${base}/privacy`;
  const title = 'Политика в отношении обработки персональных данных';
  return {
    ...buildPublicPageMetadata({
      title,
      description: DESCRIPTION,
      canonical,
      ogImageUrl: `${base}${DEFAULT_OG_IMAGE_PATH}`,
    }),
  };
}

